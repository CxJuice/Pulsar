// M3 Expressive tokens, using Motion's established spring solver (build time only).
// https://github.com/material-components/material-components-android/blob/master/lib/java/com/google/android/material/motion/res/values/tokens.xml
import { spring } from 'motion'
import { writeFile } from 'node:fs/promises'

const schemes = {
  'fast-spatial': [800, .6], 'default-spatial': [380, .8], 'slow-spatial': [200, .8],
  'fast-effects': [3800, 1], 'default-effects': [1600, 1], 'slow-effects': [800, 1],
}
let css = '/* Generated by scripts/generate_motion.mjs. Do not hand edit spring curves. */\n:root {\n'
for (const [name, [stiffness, ratio]] of Object.entries(schemes)) {
  // Android tokens use damping ratio; Motion uses damping coefficient, mass = 1.
  const generator = spring({ keyframes: [0, 1], stiffness, damping: 2 * ratio * Math.sqrt(stiffness), mass: 1, restSpeed: .01, restDelta: .001 })
  const values = []
  let time = 0
  for (; time <= 2000; time += 10) {
    const state = generator.next(time)
    values.push(state.value)
    if (state.done) break
  }
  values[values.length - 1] = 1
  css += `  --motion-${name}-duration: ${time}ms;\n`
  css += `  --motion-${name}-easing: linear(${values.map((v, i) => `${v.toFixed(5)} ${(i / (values.length - 1) * 100).toFixed(2)}%`).join(', ')});\n`
}
css += '}\n'
await writeFile(new URL('../app/assets/motion-tokens.css', import.meta.url), css)
