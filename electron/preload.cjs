const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('scKit', {
  presence: target => ipcRenderer.invoke('sc:presence', target),
  loginPresence: project => ipcRenderer.invoke('sc:presence-login', project),
  onPresence: callback => { const listener = (_event, state) => callback(state); ipcRenderer.on('sc:presence-state', listener); return () => ipcRenderer.removeListener('sc:presence-state', listener); },
  request: (action, payload = {}) => ipcRenderer.invoke('sc:request', action, payload),
  connect: (token, remember, project) => ipcRenderer.invoke('sc:connect', token, remember, project),
  login: (project) => ipcRenderer.invoke('sc:login', project),
  disconnect: () => ipcRenderer.invoke('sc:disconnect'),
  lookupCambridge: query => ipcRenderer.invoke('sc:cambridge-lookup', query),
  openCambridgeOriginal: query => ipcRenderer.invoke('sc:cambridge-open-original', query),
  fetchCommunityTranslationCandidates: () => ipcRenderer.invoke('sc:community-translation-candidates'),
  auxCustomizationOverlay: state => ipcRenderer.send('sc:aux-customization-overlay', state),
  onAuxCustomizationAction: callback => { const listener = (_event, action) => callback(action); ipcRenderer.on('sc:aux-customization-action', listener); return () => ipcRenderer.removeListener('sc:aux-customization-action', listener); },
  translatorView: state => ipcRenderer.send('sc:translator-view', state),
  getTranslationSettings: () => ipcRenderer.invoke('sc:translation-settings:get'),
  testProxy: proxy => ipcRenderer.invoke('sc:proxy-test', proxy),
  saveTranslationSettings: settings => ipcRenderer.invoke('sc:translation-settings:save', settings),
  saveTranslationSelection: selection => ipcRenderer.invoke('sc:translation-selection:save', selection),
  translateToChinese: (text, context, requestId) => ipcRenderer.invoke('sc:translate-to-chinese', text, context, requestId),
  cancelTranslation: requestId => ipcRenderer.invoke('sc:translate-cancel', requestId),
  openExternal: (url) => ipcRenderer.invoke('sc:external', url),
  exportData: (content, defaultName) => ipcRenderer.invoke('sc:export', content, defaultName),
  window: (action) => ipcRenderer.send('sc:window', action),
});
